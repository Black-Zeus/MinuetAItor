CREATE TABLE IF NOT EXISTS ai_context_documents (
  id                          CHAR(36) NOT NULL PRIMARY KEY,
  source_system               VARCHAR(60) NOT NULL DEFAULT 'minuetaitor',
  source_client_id            CHAR(36) NOT NULL,
  source_project_id           CHAR(36) NULL,
  source_minute_id            CHAR(36) NOT NULL,
  source_version_id           CHAR(36) NOT NULL,
  source_version_num          INT NOT NULL,
  status                      VARCHAR(30) NOT NULL DEFAULT 'not_indexed',
  source_hash                 CHAR(64) NULL,
  indexed_hash                CHAR(64) NULL,
  embedding_provider_config_id CHAR(36) NULL,
  embedding_binding_id        CHAR(36) NULL,
  embedding_model             VARCHAR(180) NULL,
  embedding_dimensions        INT NULL,
  qdrant_collection           VARCHAR(120) NULL,
  chunk_count                 INT NOT NULL DEFAULT 0,
  last_error                  TEXT NULL,
  indexed_at                  DATETIME NULL,
  last_checked_at             DATETIME NULL,
  deactivated_at              DATETIME NULL,
  created_at                  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at                  DATETIME NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  UNIQUE KEY uq_ai_context_document_source_version (source_system, source_minute_id, source_version_id),
  KEY idx_ai_context_documents_status (status),
  KEY idx_ai_context_documents_client_project (source_client_id, source_project_id),
  KEY idx_ai_context_documents_minute (source_minute_id),
  KEY idx_ai_context_documents_embedding_provider (embedding_provider_config_id),
  KEY idx_ai_context_documents_embedding_binding (embedding_binding_id),

  CONSTRAINT fk_ai_context_documents_client FOREIGN KEY (source_client_id) REFERENCES clients(id),
  CONSTRAINT fk_ai_context_documents_project FOREIGN KEY (source_project_id) REFERENCES projects(id),
  CONSTRAINT fk_ai_context_documents_minute FOREIGN KEY (source_minute_id) REFERENCES records(id),
  CONSTRAINT fk_ai_context_documents_version FOREIGN KEY (source_version_id) REFERENCES record_versions(id),
  CONSTRAINT fk_ai_context_documents_embedding_provider FOREIGN KEY (embedding_provider_config_id) REFERENCES ai_provider_configs(id),
  CONSTRAINT fk_ai_context_documents_embedding_binding FOREIGN KEY (embedding_binding_id) REFERENCES ai_provider_bindings(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ai_context_chunks (
  id                          CHAR(36) NOT NULL PRIMARY KEY,
  document_id                 CHAR(36) NOT NULL,
  source_system               VARCHAR(60) NOT NULL DEFAULT 'minuetaitor',
  source_client_id            CHAR(36) NOT NULL,
  source_project_id           CHAR(36) NULL,
  source_minute_id            CHAR(36) NOT NULL,
  source_version_id           CHAR(36) NOT NULL,
  source_item_id              VARCHAR(160) NOT NULL,
  item_type                   VARCHAR(60) NOT NULL,
  chunk_index                 INT NOT NULL DEFAULT 0,
  chunk_hash                  CHAR(64) NOT NULL,
  source_hash                 CHAR(64) NOT NULL,
  qdrant_collection           VARCHAR(120) NOT NULL,
  qdrant_point_id             CHAR(36) NOT NULL,
  embedding_provider_config_id CHAR(36) NOT NULL,
  embedding_binding_id        CHAR(36) NULL,
  embedding_model             VARCHAR(180) NOT NULL,
  embedding_dimensions        INT NOT NULL,
  status                      VARCHAR(30) NOT NULL DEFAULT 'indexed',
  last_error                  TEXT NULL,
  indexed_at                  DATETIME NULL,
  deactivated_at              DATETIME NULL,
  created_at                  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at                  DATETIME NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  UNIQUE KEY uq_ai_context_chunk_hash (source_system, source_minute_id, source_version_id, source_item_id, chunk_index, chunk_hash),
  KEY idx_ai_context_chunks_document (document_id),
  KEY idx_ai_context_chunks_scope (source_client_id, source_project_id, source_minute_id),
  KEY idx_ai_context_chunks_qdrant_point (qdrant_collection, qdrant_point_id),
  KEY idx_ai_context_chunks_status (status),

  CONSTRAINT fk_ai_context_chunks_document FOREIGN KEY (document_id) REFERENCES ai_context_documents(id),
  CONSTRAINT fk_ai_context_chunks_client FOREIGN KEY (source_client_id) REFERENCES clients(id),
  CONSTRAINT fk_ai_context_chunks_project FOREIGN KEY (source_project_id) REFERENCES projects(id),
  CONSTRAINT fk_ai_context_chunks_minute FOREIGN KEY (source_minute_id) REFERENCES records(id),
  CONSTRAINT fk_ai_context_chunks_version FOREIGN KEY (source_version_id) REFERENCES record_versions(id),
  CONSTRAINT fk_ai_context_chunks_embedding_provider FOREIGN KEY (embedding_provider_config_id) REFERENCES ai_provider_configs(id),
  CONSTRAINT fk_ai_context_chunks_embedding_binding FOREIGN KEY (embedding_binding_id) REFERENCES ai_provider_bindings(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ai_context_index_jobs (
  id                          CHAR(36) NOT NULL PRIMARY KEY,
  job_id                      CHAR(36) NULL,
  job_type                    VARCHAR(60) NOT NULL,
  queue_name                  VARCHAR(80) NOT NULL DEFAULT 'queue:context',
  status                      VARCHAR(30) NOT NULL DEFAULT 'queued',
  source_client_id            CHAR(36) NULL,
  source_project_id           CHAR(36) NULL,
  source_minute_id            CHAR(36) NULL,
  source_version_id           CHAR(36) NULL,
  parent_job_id               CHAR(36) NULL,
  requested_by                CHAR(36) NULL,
  attempts                    INT NOT NULL DEFAULT 0,
  max_attempts                INT NOT NULL DEFAULT 3,
  payload_json                LONGTEXT NULL,
  last_error                  TEXT NULL,
  queued_at                   DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  started_at                  DATETIME NULL,
  finished_at                 DATETIME NULL,
  created_at                  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at                  DATETIME NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  KEY idx_ai_context_index_jobs_status (status, queued_at),
  KEY idx_ai_context_index_jobs_job_id (job_id),
  KEY idx_ai_context_index_jobs_parent (parent_job_id),
  KEY idx_ai_context_index_jobs_minute (source_minute_id),
  KEY idx_ai_context_index_jobs_requested_by (requested_by),

  CONSTRAINT fk_ai_context_index_jobs_parent FOREIGN KEY (parent_job_id) REFERENCES ai_context_index_jobs(id),
  CONSTRAINT fk_ai_context_index_jobs_client FOREIGN KEY (source_client_id) REFERENCES clients(id),
  CONSTRAINT fk_ai_context_index_jobs_project FOREIGN KEY (source_project_id) REFERENCES projects(id),
  CONSTRAINT fk_ai_context_index_jobs_minute FOREIGN KEY (source_minute_id) REFERENCES records(id),
  CONSTRAINT fk_ai_context_index_jobs_version FOREIGN KEY (source_version_id) REFERENCES record_versions(id),
  CONSTRAINT fk_ai_context_index_jobs_requested_by FOREIGN KEY (requested_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS ai_context_query_runs (
  id                          CHAR(36) NOT NULL PRIMARY KEY,
  user_id                     CHAR(36) NOT NULL,
  scope_type                  VARCHAR(30) NOT NULL,
  scope_client_id             CHAR(36) NULL,
  scope_project_id            CHAR(36) NULL,
  scope_minute_id             CHAR(36) NULL,
  question_hash               CHAR(64) NOT NULL,
  question_text               LONGTEXT NOT NULL,
  status                      VARCHAR(30) NOT NULL DEFAULT 'queued',
  embedding_provider_config_id CHAR(36) NULL,
  embedding_binding_id        CHAR(36) NULL,
  embedding_model             VARCHAR(180) NULL,
  qdrant_collection           VARCHAR(120) NULL,
  answer_provider_config_id   CHAR(36) NULL,
  answer_binding_id           CHAR(36) NULL,
  answer_model                VARCHAR(180) NULL,
  answer_text                 LONGTEXT NULL,
  retrieved_chunks_count      INT NOT NULL DEFAULT 0,
  cited_chunks_count          INT NOT NULL DEFAULT 0,
  citations_json              LONGTEXT NULL,
  error_message               TEXT NULL,
  started_at                  DATETIME NULL,
  finished_at                 DATETIME NULL,
  created_at                  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at                  DATETIME NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

  KEY idx_ai_context_query_runs_user_created (user_id, created_at),
  KEY idx_ai_context_query_runs_scope (scope_type, scope_client_id, scope_project_id, scope_minute_id),
  KEY idx_ai_context_query_runs_status (status),

  CONSTRAINT fk_ai_context_query_runs_user FOREIGN KEY (user_id) REFERENCES users(id),
  CONSTRAINT fk_ai_context_query_runs_scope_client FOREIGN KEY (scope_client_id) REFERENCES clients(id),
  CONSTRAINT fk_ai_context_query_runs_scope_project FOREIGN KEY (scope_project_id) REFERENCES projects(id),
  CONSTRAINT fk_ai_context_query_runs_scope_minute FOREIGN KEY (scope_minute_id) REFERENCES records(id),
  CONSTRAINT fk_ai_context_query_runs_embedding_provider FOREIGN KEY (embedding_provider_config_id) REFERENCES ai_provider_configs(id),
  CONSTRAINT fk_ai_context_query_runs_embedding_binding FOREIGN KEY (embedding_binding_id) REFERENCES ai_provider_bindings(id),
  CONSTRAINT fk_ai_context_query_runs_answer_provider FOREIGN KEY (answer_provider_config_id) REFERENCES ai_provider_configs(id),
  CONSTRAINT fk_ai_context_query_runs_answer_binding FOREIGN KEY (answer_binding_id) REFERENCES ai_provider_bindings(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
